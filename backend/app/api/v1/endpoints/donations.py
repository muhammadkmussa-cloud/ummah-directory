@router.get("/stats")
async def donation_stats(
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
):
    total_q = await db.execute(
        select(func.count(), func.sum(Donation.amount))
        .where(Donation.status == "completed")
    )
    row = total_q.one()
    return {
        "total_donations": row[0] or 0,
        "total_amount": str(row[1] or 0),
    }
